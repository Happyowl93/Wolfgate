#!/usr/bin/env python3
"""Recolours the converted borg skins into PDV and TSF variants.

    python Tools/_WF/BorgSkins/recolor.py

Reads the engineering, medical and security skins that convert.py wrote and rebuilds, for each faction, their RSIs
under Resources/Textures/_WF/BorgSkins/<size>/<faction>, plus faction_subtypes.yml, faction_chassis.yml and
faction_chassis.ftl. Run it again after convert.py. The mapping is colour to colour, so shading steps are kept: a
skin's main accent hue takes the faction's body ramp, every other colour becomes plain metal, and the eyes take the
faction's lamp hue. The dullahans are left out: their artists agreed to the port, not to recolours.
"""
import colorsys
import json
import re
import shutil
from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
TEXTURES = ROOT / 'Resources/Textures'
PROTOTYPES = ROOT / 'Resources/Prototypes/_WF/BorgSkins'
LOCALE = ROOT / 'Resources/Locale/en-US/_WF/BorgSkins'
HEADER = '# Generated by Tools/_WF/BorgSkins/recolor.py from the skins convert.py wrote.\n'

# Body ramp, dark to light, and lamp hue in degrees, both sampled from the stock _Mono chassis.
FACTIONS = {
    'PDV': {'ramp': ['#332a1f', '#443c30', '#564c3d', '#746754', '#93836f'], 'lamp': 127},
    'TSF': {'ramp': ['#1f2432', '#2b3244', '#3f4962', '#535c76', '#6e7891'], 'lamp': 219},
}
# Source department -> (faction role, the source body state, the role's body state).
ROLES = {
    'Engineering': ('Engineer', 'engineer', 'engineer'),
    'Medical': ('Medical', 'medical', 'medical'),
    'Security': ('Assault', 'robot', 'assault'),
}
SKIPPED_BODIES = ('dullahan',)
POSES = ('rest', 'sit', 'bellyup', 'wreck', 'tipped')
UNTOUCHED = ('credit',)

GREY_LO, GREY_HI = 0x26, 0x8c   # the stock chassis neutrals run #262626 to #787878; a little headroom for highlights
CHROMA = 0.22                   # below this saturation a colour counts as neutral
PLATING_LUM = 0x70              # neutrals at least this bright are plating, darker ones frame and joints
HUE_WIDTH = 0.09


def rgb(text):
    return tuple(int(text[i:i + 2], 16) for i in (1, 3, 5))


def lum(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def hsv(c):
    return colorsys.rgb_to_hsv(c[0] / 255, c[1] / 255, c[2] / 255)


def ramp_at(ramp, t):
    t = min(max(t, 0.0), 1.0) * (len(ramp) - 1)
    i = min(int(t), len(ramp) - 2)
    return tuple(round(ramp[i][k] + (ramp[i + 1][k] - ramp[i][k]) * (t - i)) for k in range(3))


def hue_distance(a, b):
    d = abs(a - b) % 1.0
    return min(d, 1 - d)


def body_map(colours, faction):
    """Maps every body colour (a Counter of RGB to pixel count) to its faction colour."""
    ramp = [rgb(c) for c in FACTIONS[faction]['ramp']]
    chromatic = {c: n for c, n in colours.items() if hsv(c)[1] >= CHROMA and hsv(c)[2] > 0.12}
    bins = Counter()
    for c, n in chromatic.items():
        bins[round(hsv(c)[0] * 24) % 24] += n
    main = max(bins, key=bins.get) / 24 if bins else None
    primary = [c for c in chromatic if main is not None and hue_distance(hsv(c)[0], main) <= HUE_WIDTH]

    # A body that is mostly bare plating has too little accent to carry the faction: its light plating takes the ramp too.
    if sum(colours[c] for c in primary) < 0.3 * sum(colours.values()):
        primary += [c for c in colours if c not in primary and hsv(c)[1] < CHROMA and lum(c) >= PLATING_LUM]

    levels = [lum(c) for c in primary] or [0, 1]
    lo, hi = min(levels), max(levels)
    rest = [lum(c) for c in colours if c not in primary] or [0, 1]
    rest_lo, rest_hi = min(rest), max(rest)

    mapped = {}
    for c in colours:
        if c in primary:
            mapped[c] = ramp_at(ramp, (lum(c) - lo) / max(hi - lo, 1))
            continue
        # Other hues and neutrals become the faction's plain metal, squeezed into its value range.
        v = lum(c)
        if rest_hi > GREY_HI and v > GREY_LO:
            v = rest_lo + (v - rest_lo) * (GREY_HI - min(rest_lo, GREY_LO)) / max(rest_hi - rest_lo, 1)
        grey = round(min(max(v, 0), 255))
        mapped[c] = (grey, grey, grey)
    return mapped


def lamp_colour(c, faction):
    h, s, v = hsv(c)
    if s < 0.12:
        return c
    # Hue only: a lamp's own saturation steps are its shading.
    r, g, b = colorsys.hsv_to_rgb(FACTIONS[faction]['lamp'] / 360, s, v)
    return round(r * 255), round(g * 255), round(b * 255)


def repaint(image, colour_of):
    image = image.convert('RGBA')
    pixels = image.load()
    for y in range(image.height):
        for x in range(image.width):
            r, g, b, a = pixels[x, y]
            if a:
                pixels[x, y] = (*colour_of((r, g, b)), a)
    return image


def recolour(src, dst, faction, source_state, role_state):
    """Writes the faction RSI. The faction borg types show <state>_l as both eyes and lamp, so it is the skin's eyes."""
    meta = json.loads((src / 'meta.json').read_text(encoding='utf-8'))
    by_name = {state['name']: state for state in meta['states']}
    # (source state, output state, is it a light layer)
    wanted = [(source_state, role_state, False), (f'{source_state}_e', f'{role_state}_l', True),
              (f'{source_state}_moving', f'{role_state}_moving', False),
              (f'{source_state}_e_moving', f'{role_state}_l_moving', True)]
    wanted += [(pose, pose, False) for pose in POSES + UNTOUCHED]
    wanted = [entry for entry in wanted if entry[0] in by_name]

    colours = Counter()
    for source, _, light in wanted:
        if light or source in UNTOUCHED:
            continue
        for count, pixel in Image.open(src / f'{source}.png').convert('RGBA').getcolors(1 << 20):
            if pixel[3]:
                colours[pixel[:3]] += count
    mapped = body_map(colours, faction)

    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    states = []
    for source, output, light in wanted:
        image = Image.open(src / f'{source}.png')
        if source not in UNTOUCHED:
            image = repaint(image, (lambda c: lamp_colour(c, faction)) if light else (lambda c: mapped.get(c, c)))
        image.save(dst / f'{output}.png')
        states.append({**by_name[source], 'name': output})
    meta['states'] = states
    meta['copyright'] += f', recoloured for the {faction} by Tools/_WF/BorgSkins/recolor.py'
    (dst / 'meta.json').write_text(json.dumps(meta, indent=2) + '\n', encoding='utf-8', newline='\n')


def main():
    blocks = (PROTOTYPES / 'subtypes.yml').read_text(encoding='utf-8').replace('\r\n', '\n').split('\n\n')
    extras = {}
    for block in blocks:
        if '- type: wfBorgSkin' in block:
            lines = block.strip().split('\n')
            extras[lines[1].split()[-1]] = lines[2:]
    names = dict(re.findall(r'^ent-(\S+) = (.+)$', (LOCALE / 'chassis.ftl').read_text(encoding='utf-8'), re.M))

    subtypes, chassis, locale = [], [], []
    for block in blocks:
        match = re.search(r'- type: borgSubtype\n  id: (\S+)\n.*\n  spritePath: (\S+)\n  dummyPrototype: (\S+)', block)
        if not match:
            continue
        source_id, path, source_dummy = match.groups()
        _, _, size, department, rsi = path.split('/')
        body = rsi[:-len('.rsi')]
        if department not in ROLES or body.startswith(SKIPPED_BODIES):
            continue
        role, source_state, role_state = ROLES[department]
        ident = source_id[len('WFBorgSkin' + department):]
        name = names[source_dummy].rsplit(' ', 2)[0]
        for faction in FACTIONS:
            target = f'_WF/BorgSkins/{size}/{faction}/{role}/{rsi}'
            recolour(TEXTURES / path, TEXTURES / target, faction, source_state, role_state)
            tag = f'{faction.capitalize()}{role}{ident}'
            subtypes.append(f'- type: borgSubtype\n  id: WFBorgSkin{tag}\n  parentBorgType: {faction.lower()}{role.lower()}\n'
                            f'  spritePath: {target}\n  dummyPrototype: WFBorgChassis{tag}\n\n'
                            f'- type: wfBorgSkin\n  id: WFBorgSkin{tag}\n' + '\n'.join(extras.get(source_id, [])) + '\n')
            chassis.append(f'- type: entity\n  id: WFBorgChassis{tag}\n  parent: {faction}BorgChassis{role}\n'
                           f'  categories: [ HideSpawnMenu ]\n  components:\n  - type: BorgSwitchableSubtype\n'
                           f'    borgSubtype: WFBorgSkin{tag}\n')
            locale.append(f'ent-WFBorgChassis{tag} = {name} {faction} {role.lower()} cyborg\n')

    for path, body in ((PROTOTYPES / 'faction_subtypes.yml', '\n'.join(subtypes)),
                       (PROTOTYPES / 'faction_chassis.yml', '\n'.join(chassis)),
                       (LOCALE / 'faction_chassis.ftl', ''.join(locale))):
        path.write_text(HEADER + '\n' + body, encoding='utf-8', newline='\n')
    print(f'{len(subtypes)} faction skins')


if __name__ == '__main__':
    main()
